const patch = (f, pairs) => {
  let s = fs.readFileSync(f, 'utf8')
  for (const [a, b] of pairs) {
    if (!s.includes(a)) { miss.push(f + ': ' + a.slice(0, 40)); continue }
    s = s.split(a).join(b)
  }
  fs.writeFileSync(f, s)
}

