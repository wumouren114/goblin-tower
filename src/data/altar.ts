/**
 * 「祭坛」与「神秘祭坛」文案数据（纯数据 + 类型，不依赖任何运行时模块）。
 *
 * 四座祭坛各自带有不同性格：
 * - card    ：像在讨价（交出一张道具卡，换更强的永久属性）
 * - hp      ：像在哀悼（失去一部分生命上限，换取攻击与魔力）
 * - both    ：像在公证（同时交出卡与生命上限，换一次专武方向）
 * - mystery ：像在赌场（投入金币，听凭高塔随手落子）
 */

export interface AltarFlavor {
  id: 'card' | 'hp' | 'both' | 'mystery'
  title: string
  icon: string
  /** 玩家走近时祭坛的低语（一句，阴冷但不吓人） */
  whisper: string
  /** 描述「献上什么、得到什么」，不写具体数值 */
  offer: string
  /** 献祭完成的回响（一句） */
  accept: string
  /** 献祭之后的余韵（一句，留白） */
  regret: string
}

export interface MysteryOutcomeText {
  kind: 'jackpot' | 'card' | 'refund' | 'nothing'
  /** 结果台词（一句） */
  line: string
  /** 余韵（一句，可留白） */
  echo: string
}

